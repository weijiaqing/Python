let fail = 0;
console.log("=== 발음 (phonetic reading) ===");
for (const [ko, want] of READ) {
  const got = KO.pronounce(ko);
  if (got !== want) { fail++; console.log(`FAIL  ${ko}  -> [${got}]  expected [${want}]`); }
}
console.log("=== 로마자 (Revised Romanization) ===");
for (const [ko, want] of ROMAN) {
  const got = KO.romanize(ko);
  if (got !== want) { fail++; console.log(`FAIL  ${ko}  -> ${got}  expected ${want}`); }
}
console.log(fail ? `\n${fail} failing of ${READ.length + ROMAN.length}` : `\nall ${READ.length + ROMAN.length} pass`);
